            });
    }

    private static void BodyCell(
        TableDescriptor table,
        string text,
        bool alignRight,
        string? color = null,
        bool bold = false)
    {
        table.Cell()
            .BorderBottom(0.5f)
            .BorderColor("#EEF2F7")
            .PaddingVertical(4.2f)
            .PaddingHorizontal(3)
            .Element(cell =>
            {
                var aligned = alignRight
                    ? cell.AlignRight()
                    : cell.AlignLeft();

                var descriptor = aligned
                    .Text(Safe(text, "-"))
                    .FontSize(6.2f)
                    .FontColor(color ?? Slate);

                if (bold)
                {
                    descriptor.Bold();
                }
            });
    }

    private static void ComparisonRow(
        TableDescriptor table,
        string label,
        decimal previous,
        decimal current,
        double change,
        bool higherIsBetter)
    {
        BodyCell(table, label, false);
        BodyCell(table, Money(previous), true);
        BodyCell(table, Money(current), true);

        var good = higherIsBetter
            ? change >= 0
            : change <= 0;

        BodyCell(
            table,
            $"{ChangeArrow(change)} {Math.Abs(change):F1}%",
            true,
            good ? Green : Red,
            true);
    }

