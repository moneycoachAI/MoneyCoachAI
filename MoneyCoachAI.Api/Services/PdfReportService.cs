    public byte[] GenerateMonthlyReportPdf(
        int month,
        int year,
        MonthlyReportPdfResponse report)
    {
        QuestPDF.Settings.License = LicenseType.Community;

        var monthName = new DateTime(year, month, 1)
            .ToString("MMMM yyyy");

        var document = Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(10);

                page.DefaultTextStyle(style =>
                    style
                        .FontSize(7.2f)
                        .FontColor(Slate));

                page.Content()
                    .Column(column =>
                    {
                        column.Spacing(7);

                        column.Item()
                            .Element(c =>
                                ComposeHeader(
                                    c,
                                    monthName,
                                    report));

                        // AI ADVISOR AT TOP
                        column.Item()
                            .Element(c =>
                                ComposeAiAdvisor(
                                    c,
                                    report));

                        column.Item()
                            .Row(row =>
                            {
                                row.Spacing(5);

                                row.RelativeItem()
                                    .Element(c =>
                                        ComposeFinancialOverview(
                                            c,
                                            report));

                                row.RelativeItem()
                                    .Element(c =>
                                        ComposeMonthlyComparison(
                                            c,
                                            report));
                            });

                        // Spending and budget full-width: better alignment/readability
                        column.Item()
                            .Element(c =>
                                ComposeSpendingAndBudget(
                                    c,
                                    report));

                        column.Item()
                            .Element(c =>
                                ComposeSmartAlerts(
                                    c,
                                    report));

                        column.Item()
                            .Element(c =>
                                ComposeMonthlyFocus(
                                    c,
                                    report));

                        column.Item()
                            .Element(c =>
                                ComposeBottomSummary(
                                    c,
                                    report));
                    });

                page.Footer()
                    .PaddingTop(3)
                    .Row(row =>
                    {
                        row.RelativeItem()
                            .Text(
                                $"Generated by MoneyCoachAI • {DateTime.Now:dd MMM yyyy}")
                            .FontSize(6.2f)
                            .FontColor(SlateLight);

                        row.RelativeItem()
                            .AlignRight()
                            .DefaultTextStyle(style =>
                                style
                                    .FontSize(6.2f)
                                    .FontColor(SlateLight))
                            .Text(text =>
                            {
                                text.Span("Monthly Financial Statement • ");
                                text.CurrentPageNumber();
                                text.Span(" / ");
                                text.TotalPages();
                            });
                    });
            });
        });

        return document.GeneratePdf();
    }

